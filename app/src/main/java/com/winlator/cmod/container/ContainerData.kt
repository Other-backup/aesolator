            containerVariant = savedMap.stringValue("containerVariant", Container.DEFAULT_VARIANT),
            wineVersion = savedMap.stringValue("wineVersion", WineInfo.MAIN_WINE_VERSION.identifier()),
            emulator = savedMap.stringValue("emulator", Container.DEFAULT_EMULATOR),
            fexcoreVersion = savedMap.stringValue("fexcoreVersion", DefaultVersion.FEXCORE),
            fexcoreTSOMode = savedMap.stringValue("fexcoreTSOMode", "Fast"),
            fexcoreX87Mode = savedMap.stringValue("fexcoreX87Mode", "Fast"),
            fexcoreMultiBlock = savedMap.stringValue("fexcoreMultiBlock", "Disabled"),
            fexcorePreset = savedMap.stringValue("fexcorePreset", FEXCorePreset.INTERMEDIATE),
