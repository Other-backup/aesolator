            videoPciDeviceID = savedMap.intValue("videoPciDeviceID", 1728),
            offScreenRenderingMode = savedMap.stringValue("offScreenRenderingMode", "fbo"),
            strictShaderMath = savedMap.booleanValue("strictShaderMath", true),
            useDRI3 = savedMap.booleanValue("useDRI3", true),
            videoMemorySize = savedMap.stringValue("videoMemorySize", "2048"),
            mouseWarpOverride = savedMap.stringValue("mouseWarpOverride", "disable"),
            shaderBackend = savedMap.stringValue("shaderBackend", "glsl"),
            useGLSL = savedMap.stringValue("useGLSL", "enabled"),
            sdlControllerAPI = savedMap.booleanValue("sdlControllerAPI", true),
            useSteamInput = savedMap.booleanValue("useSteamInput", false),
            enableXInput = savedMap.booleanValue("enableXInput", true),
            enableDInput = savedMap.booleanValue("enableDInput", true),
            dinputMapperType = savedMap.byteValue("dinputMapperType", 1),
            disableMouseInput = savedMap.booleanValue("disableMouseInput", false),
            touchscreenMode = savedMap.booleanValue("touchscreenMode", false),
            shooterMode = savedMap.booleanValue("shooterMode", true),
            gestureConfig = savedMap.stringValue("gestureConfig", ""),
            externalDisplayMode = savedMap.stringValue("externalDisplayMode", "off"),
            externalDisplaySwap = savedMap.booleanValue("externalDisplaySwap", false),
            language = savedMap.stringValue("language", "english"),
            forceDlc = savedMap.booleanValue("forceDlc", false),
            steamOfflineMode = savedMap.booleanValue("steamOfflineMode", false),
            useLegacyDRM = savedMap.booleanValue("useLegacyDRM", false),
            unpackFiles = savedMap.booleanValue("unpackFiles", false),
            suspendPolicy = savedMap.stringValue("suspendPolicy", "manual"),
            portraitMode = savedMap.booleanValue("portraitMode", false),
            sharpnessEffect = savedMap.stringValue("sharpnessEffect", "None"),
            sharpnessLevel = savedMap.intValue("sharpnessLevel", 100),
            sharpnessDenoise = savedMap.intValue("sharpnessDenoise", 100),
        )

