            box86Version = savedMap.stringValue("box86Version", DefaultVersion.BOX64),
            box64Version = savedMap.stringValue("box64Version", DefaultVersion.BOX64),
            box86Preset = savedMap.stringValue("box86Preset", Box86_64Preset.COMPATIBILITY),
            box64Preset = savedMap.stringValue("box64Preset", Box86_64Preset.COMPATIBILITY),
