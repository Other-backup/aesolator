            screenSize = savedMap.stringValue("screenSize", Container.DEFAULT_SCREEN_SIZE),
            envVars = savedMap.stringValue("envVars", Container.DEFAULT_ENV_VARS),
            graphicsDriver = savedMap.stringValue("graphicsDriver", Container.DEFAULT_GRAPHICS_DRIVER),
            graphicsDriverVersion = savedMap.stringValue("graphicsDriverVersion", ""),
            graphicsDriverConfig = savedMap.stringValue("graphicsDriverConfig", ""),
            dxwrapper = savedMap.stringValue("dxwrapper", Container.DEFAULT_DXWRAPPER),
            dxwrapperConfig = savedMap.stringValue("dxwrapperConfig", ""),
            audioDriver = savedMap.stringValue("audioDriver", Container.DEFAULT_AUDIO_DRIVER),
            wincomponents = savedMap.stringValue("wincomponents", Container.DEFAULT_WINCOMPONENTS),
            drives = savedMap.stringValue("drives", Container.DEFAULT_DRIVES),
            execArgs = savedMap.stringValue("execArgs", ""),
            executablePath = savedMap.stringValue("executablePath", ""),
